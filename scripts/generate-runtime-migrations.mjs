import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const migrationsDirectory = resolve(projectRoot, "drizzle");
const journal = JSON.parse(
  readFileSync(resolve(migrationsDirectory, "meta/_journal.json"), "utf8"),
);

const migrations = journal.entries.map((entry) => {
  const name = `${entry.tag}.sql`;
  const sql = readFileSync(resolve(migrationsDirectory, name), "utf8");
  return {
    name,
    statements: sql
      .split("--> statement-breakpoint")
      .map((statement) => statement.trim())
      .filter(Boolean),
  };
});

const output = `// This file is generated by scripts/generate-runtime-migrations.mjs.
// Regenerate it whenever a migration is added or changed.
import type { RuntimeDatabaseMigration } from "./setup-database-migrations.types";

export const runtimeDatabaseMigrations: RuntimeDatabaseMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(
  resolve(projectRoot, "src/lib/setup-database-migrations.config.ts"),
  output,
);
